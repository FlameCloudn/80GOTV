    CREATE TABLE IF NOT EXISTS matches (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    event_id INTEGER,
    team1_id INTEGER,
    team2_id INTEGER,
    team1_score INTEGER DEFAULT 0,
    team2_score INTEGER DEFAULT 0,
    team1_players TEXT,
    team2_players TEXT,
    match_time TEXT,
    bo_format TEXT,
    stage TEXT,
    status TEXT,
    map_pool TEXT,
    map1 TEXT,
    map1_t1 INTEGER DEFAULT 0,
    map1_t2 INTEGER DEFAULT 0,
    map1_picked_by TEXT,
    map2 TEXT,
    map2_t1 INTEGER DEFAULT 0,
    map2_t2 INTEGER DEFAULT 0,
    map2_picked_by TEXT,
    map3 TEXT,
    map3_t1 INTEGER DEFAULT 0,
    map3_t2 INTEGER DEFAULT 0,
    map3_picked_by TEXT,
    has_map3 INTEGER DEFAULT 1,
    map4 TEXT,
    map4_t1 INTEGER DEFAULT 0,
    map4_t2 INTEGER DEFAULT 0,
    map4_picked_by TEXT,
    has_map4 INTEGER DEFAULT 1,
    map5 TEXT,
    map5_t1 INTEGER DEFAULT 0,
    map5_t2 INTEGER DEFAULT 0,
    map5_picked_by TEXT,
    has_map5 INTEGER DEFAULT 1,
    bp_process TEXT,
    bp_password TEXT DEFAULT NULL,
    bp_state TEXT DEFAULT NULL,
    roster_snapshot TEXT,
    team1_registration_id INTEGER,
    team2_registration_id INTEGER,
    decider_knife_winner TEXT,
    decider_start_side TEXT,
    stream_url TEXT,
    stream_info TEXT,
    map_halves TEXT,
    watch_urls TEXT,
    server_address TEXT,
    server_password TEXT,
    demo_file TEXT,
    slug TEXT,
    is_test_mode INTEGER NOT NULL DEFAULT 0,
    created_at TEXT DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(event_id) REFERENCES events(id),
    FOREIGN KEY(team1_id) REFERENCES teams(id),
    FOREIGN KEY(team2_id) REFERENCES teams(id),
    FOREIGN KEY(team1_registration_id) REFERENCES event_registrations(id) ON DELETE SET NULL,
    FOREIGN KEY(team2_registration_id) REFERENCES event_registrations(id) ON DELETE SET NULL
);

    CREATE TABLE IF NOT EXISTS match_slug_aliases (
    slug TEXT PRIMARY KEY,
    match_id INTEGER NOT NULL
);
